val Strings.player: PlayerStrings get() = if (this === ArStrings) ArPlayerStrings else EnPlayerStrings

/** Fills `%1$s`-style placeholders without locale-specific digit shaping. */
fun String.fill(vararg args: String): String = String.format(Locale.ROOT, this, *args)
