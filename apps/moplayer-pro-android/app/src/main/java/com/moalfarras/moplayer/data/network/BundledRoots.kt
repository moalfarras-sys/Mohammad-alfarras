/**
 * Trusts what the platform trusts plus [extraRoots]. It never trusts everything and leaves
 * hostname verification to OkHttp: a chain is accepted when either the platform store or the
 * bundled roots validate it. Both delegates are built lazily on first use.
 */
internal class PlatformPlusBundledTrustManager(
    private val extraRoots: () -> List<X509Certificate> = { BundledRoots.certificates },
) : X509TrustManager {
    private val platform: X509TrustManager by lazy { trustManagerFor(null) }
    private val bundled: X509TrustManager by lazy {
        val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply {
            load(null, null)
            extraRoots().forEachIndexed { index, certificate -> setCertificateEntry("bundled-$index", certificate) }
        }
        trustManagerFor(store)
    }

    override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) =
        platform.checkClientTrusted(chain, authType)

    override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) {
        try {
            platform.checkServerTrusted(chain, authType)
        } catch (platformFailure: CertificateException) {
            try {
                bundled.checkServerTrusted(chain, authType)
            } catch (bundledFailure: CertificateException) {
                platformFailure.addSuppressed(bundledFailure)
                throw platformFailure
            }
        }
    }

    override fun getAcceptedIssuers(): Array<X509Certificate> = platform.acceptedIssuers + bundled.acceptedIssuers

    private fun trustManagerFor(store: KeyStore?): X509TrustManager =
        TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
            .apply { init(store) }
            .trustManagers
            .filterIsInstance<X509TrustManager>()
            .first()
}
