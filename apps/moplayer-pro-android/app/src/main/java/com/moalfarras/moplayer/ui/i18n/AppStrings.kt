/**
 * Arabic count agreement for seconds (CLDR plural rules): 1 and 2 have their own words, then the
 * last two digits decide: 3–10 → ثوانٍ, 11–99 → ثانية, 00–02 (100, 200…) → ثانية.
 */
internal fun arabicSeconds(seconds: Long): String {
    val count = seconds.toString().ltr()
    return when {
        seconds == 1L -> "ثانية واحدة"
        seconds == 2L -> "ثانيتين"
        seconds % 100 in 3L..10L -> "$count ثوانٍ"
        else -> "$count ثانية"
    }
}

